# Strict validation: Check for asterisks or brackets
for article in new_articles:
    for field in ["title", "summary", "content"]:
        val = article[field]
        if "*" in val:
            print(f"ERROR: Asterisk found in {article['id']} {field}")
            sys.exit(1)
        if field == "title" and ("【" in val or "】" in val):
            print(f"ERROR: Brackets found in {article['id']} title")
            sys.exit(1)
    for t in article["takeaways"]:
        if "*" in t:
            print(f"ERROR: Asterisk found in takeaway of {article['id']}")
            sys.exit(1)

with open(DATA_PATH, "r", encoding="utf-8") as f:
    current_data = json.load(f)

# Filter out duplicates if any
existing_ids = {a["id"] for a in current_data}
to_add = [a for a in new_articles if a["id"] not in existing_ids]

if not to_add:
    print("Articles already present.")
else:
    updated_data = to_add + current_data
    with open(DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(updated_data, f, ensure_ascii=False, indent=2)
    with open(PUBLIC_PATH, "w", encoding="utf-8") as f:
        json.dump(updated_data, f, ensure_ascii=False, indent=2)
    print(f"Successfully added {len(to_add)} articles to {DATA_PATH} and {PUBLIC_PATH}.")
