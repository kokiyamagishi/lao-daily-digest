# Strict validation
for item in new_articles:
    for field in ['title', 'summary', 'content']:
        if '*' in item[field]:
            raise ValueError(f"Asterisk detected in {item['id']} field {field}")
    for t in item['takeaways']:
        if '*' in t:
            raise ValueError(f"Asterisk detected in takeaway: {t}")
    if item['title'].startswith('【'):
        raise ValueError(f"Category bracket detected in title: {item['title']}")

with open('src/data/news.json', 'r', encoding='utf-8') as f:
    existing = json.load(f)

existing_ids = {a['id'] for a in existing}
filtered_new = [a for a in new_articles if a['id'] not in existing_ids]

if not filtered_new:
    print("No new articles to add.")
else:
    updated = filtered_new + existing
    with open('src/data/news.json', 'w', encoding='utf-8') as f:
        json.dump(updated, f, ensure_ascii=False, indent=2)
    with open('public/news.json', 'w', encoding='utf-8') as f:
        json.dump(updated, f, ensure_ascii=False, indent=2)
    print(f"Successfully added {len(filtered_new)} new articles for 2026-10-31.")
