# Asterisk check
for article in new_articles:
    for key, val in article.items():
        if isinstance(val, str) and "*" in val:
            raise ValueError(f"Asterisk found in {article['id']} field {key}: {val}")
        elif isinstance(val, list):
            for item in val:
                if isinstance(item, str) and "*" in item:
                    raise ValueError(f"Asterisk found in {article['id']} list field {key}: {item}")
        # Title bracket check
        if key == "title" and re.search(r"^【.*?】", val):
            raise ValueError(f"Category prefix found in title of {article['id']}: {val}")

# Avoid duplicates
existing_ids = {a["id"] for a in news_data}
filtered_new = [a for a in new_articles if a["id"] not in existing_ids]

if not filtered_new:
    print("All articles already present in news.json!")
else:
    updated_data = filtered_new + news_data
    with open(news_path, "w", encoding="utf-8") as f:
        json.dump(updated_data, f, ensure_ascii=False, indent=2)
    print(f"Successfully added {len(filtered_new)} articles to {news_path}.")
