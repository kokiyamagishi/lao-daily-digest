# Strict validation: Check for asterisks or brackets
for article in new_articles:
    for field in ["title", "summary", "content"]:
        val = article[field]
        if "*" in val:
            print(f"ERROR: Asterisk found in {article['id']} {field}")
            sys.exit(1)
        if field == "title" and ("【" in val or "】" in val):
            print(f"ERROR: Brackets found in {article['id']} title")
            sys.exit(1)
    for t in article["takeaways"]:
        if "*" in t:
            print(f"ERROR: Asterisk found in takeaway of {article['id']}")
            sys.exit(1)

with open(DATA_PATH, "r", encoding="utf-8") as f:
    current_data = json.load(f)

# Filter out duplicates if any
